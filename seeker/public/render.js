canvas.addEventListener('auxclick', e => e.preventDefault());
// Holding a button and moving drags (as in DreamSeeker, with any button): MouseDrag as the target changes,
// MouseDrop on release. The pointer may leave the map meanwhile: the page follows it, and a drop off the map
// goes to nothing. As in DreamSeeker, nothing is drawn under the pointer: the drop only has its effect in the game.
const sameAtom = (a, b) => a && b && a.type === b.type && a.ref === b.ref;
// (off the map there is no icon or screen position: only the button and modifier keys)
const offMapParams = (e, btn) => [...btn, ...(e.shiftKey ? ['shift=1'] : []), ...(e.ctrlKey ? ['ctrl=1'] : []), ...(e.altKey ? ['alt=1'] : [])].join(';');
const dragMessage = (e, tg, drop) => ({ t: 'drag', drop, src: pressed.src, over: tg && tg.src, srcLoc: pressed.loc, overLoc: tg && tg.loc,
	params: tg ? mouseParams(e, tg.hit, pressed.btn) : offMapParams(e, pressed.btn) });
window.addEventListener('mousemove', e => {
	if (!pressed) return;
	if (!pressed.dragging && Math.hypot(e.clientX - pressed.x, e.clientY - pressed.y) < 5) return;
	pressed.dragging = true;
	const tg = e.target === canvas ? mouseTarget(e) : null, now = performance.now();
	if (sameAtom(tg && tg.src, pressed.over) && now - lastDrag < 50) return;
	pressed.over = tg && tg.src; lastDrag = now;
	sendMouse({ ...dragMessage(e, tg, false), what: tg && tg.hit && tg.hit.h.d.a.name });
});
window.addEventListener('mouseup', e => {
	if (!pressed || e.button !== pressed.button) return;
	const tg = e.target === canvas ? mouseTarget(e) : null;
	if (pressed.dragging) { sendMouse({ ...dragMessage(e, tg, true), what: tg && tg.hit && tg.hit.h.d.a.name }); pressed = null; return; }
	const at = tg || pressed;
	// MouseUp on whatever is under the cursor now; Click only when released over the pressed atom
	sendMouse({ t: 'mouse', cmds: sameAtom(at.src, pressed.src) ? [5, 3] : [5], src: at.src, loc: at.loc, params: mouseParams(e, at.hit, pressed.btn) });
	pressed = null;
});

// ---------- right-click menu ----------
// As in DreamSeeker: every atom on the clicked tile (top first, with a small icon) and a submenu of its verbs.
// A HUD object gets its verbs straight away.
const atomKey = b => b.kind === 'turf' ? 'turf:' + b.x + ',' + b.y : b.kind + ':' + b.ref;
function menuAtoms(base) {
	if (base.kind === 'screen') return [{ atom: atomOf(base), app: appOf(base), key: atomKey(base) }];
	const out = [], seen = new Set();
	for (let i = drawn.length - 1; i >= 0; i--) {
		const b = drawn[i].d.base;
		if (b.kind === 'screen' || b.vis || b.x !== base.x || b.y !== base.y || drawn[i].d.mo === 0) continue;
		const key = atomKey(b);
		if (seen.has(key)) continue;
		seen.add(key);
		out.push({ atom: atomOf(b), app: appOf(b), key });
	}
	return out;
}
// The atom's sprites from the last frame (overlays included, no transforms) on a small canvas
function menuIcon(key) {
	const parts = drawn.filter(h => h.ic && h.rect && !h.d.base.image && !h.d.base.vis && atomKey(h.d.base) === key);
	const c = document.createElement('canvas');
	c.width = c.height = 32;
	c.className = 'mi';
	if (!parts.length) return c;
	const own = parts.find(h => h.d.a.id === appOf(parts[0].d.base)) || parts[0], s = viewport.scale;
	const g = c.getContext('2d');
	g.imageSmoothingEnabled = false;
	for (const h of parts) {
		const ox = Math.round((h.dx - own.dx) / s), oy = Math.round((h.dy - own.dy) / s);
		g.drawImage(h.ic.img, h.rect.sx, h.rect.sy, h.rect.w, h.rect.h, ox * 32 / own.rect.w, oy * 32 / own.rect.h, h.rect.w * 32 / own.rect.w, h.rect.h * 32 / own.rect.h);
	}
	return c;
}
const nameOfKey = key => { const [k, r] = key.split(':'); const id = k === 'turf' ? state.turfs.get(r) : state.objs.get(key)?.app; return state.apps.get(id)?.name || k; };
let menuEl = null, subEl = null;
function closeSub() { if (subEl) { subEl.remove(); subEl = null; } }
function closeMenu() { closeSub(); if (menuEl) { menuEl.remove(); menuEl = null; } }
function placeMenu(el, x, y, flipX) {
	document.body.appendChild(el);
	if (x + el.offsetWidth > innerWidth - 4 && flipX !== undefined) x = flipX - el.offsetWidth;
	el.style.left = Math.max(0, Math.min(x, innerWidth - el.offsetWidth - 4)) + 'px';
	el.style.top = Math.max(0, Math.min(y, innerHeight - el.offsetHeight - 4)) + 'px';
}
function verbList(g) {
	const el = document.createElement('div');
	el.className = 'ctxmenu';
	for (const it of g.items) {
		const b = document.createElement('button');
		b.textContent = it.name;
		b.onclick = () => { ws.send(JSON.stringify({ t: 'menuPick', id: it.id, mode: it.mode, atom: g.atom })); closeMenu(); };
		el.appendChild(b);
	}
	return el;
}
function showMenu(m) {
	closeMenu();
	const groups = m.groups || [];
	if (!groups.length) return;
	const [x, y] = m.at || [0, 0];
	if (groups.length === 1 && !groups[0].key) { menuEl = verbList(groups[0]); placeMenu(menuEl, x, y); return; }
	menuEl = document.createElement('div');
	menuEl.className = 'ctxmenu';
	for (const g of groups) {
		const b = document.createElement('button');
		b.className = 'atom';
		b.append(menuIcon(g.key), Object.assign(document.createElement('span'), { textContent: nameOfKey(g.key) }), Object.assign(document.createElement('i'), { textContent: '▸' }));
		const open = () => {
			if (subEl && subEl._for === b) return;
			closeSub();
			for (const o of menuEl.children) o.classList.toggle('on', o === b);
			subEl = verbList(g); subEl._for = b;
			const r = b.getBoundingClientRect();
			placeMenu(subEl, r.right, r.top - 4, r.left);
		};
		b.onmouseenter = open;
		b.onclick = open;
		menuEl.appendChild(b);
	}
	placeMenu(menuEl, x, y);
}
